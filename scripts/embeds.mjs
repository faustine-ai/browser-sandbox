// Bundles the two pieces of code that run outside the page — the frame relay
// and the worker runtime — into strings the library embeds, and computes the
// CSP hash of the relay script so the frame document needs no nonce.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';

mkdirSync('src/generated', { recursive: true });

async function bundle(entry) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    platform: 'browser',
    target: 'es2020',
    format: 'iife',
    minify: true,
    legalComments: 'none',
  });
  return result.outputFiles[0].text.trim();
}

const relay = await bundle('src/frame/relay.ts');
const worker = await bundle('src/worker/entry.ts');
const relayHash = createHash('sha256').update(relay).digest('base64');
const workerHash = createHash('sha256').update(worker).digest('hex').slice(0, 16);

writeFileSync(
  'src/generated/embeds.ts',
  `// Generated by scripts/embeds.mjs — do not edit.\n` +
    `export const RELAY_SOURCE = ${JSON.stringify(relay)};\n` +
    `export const RELAY_SHA256 = ${JSON.stringify(relayHash)};\n` +
    `export const WORKER_SOURCE = ${JSON.stringify(worker)};\n` +
    `export const WORKER_HASH = ${JSON.stringify(workerHash)};\n`,
);
console.log(`embeds: relay ${relay.length} B (sha256 ${relayHash.slice(0, 12)}…), worker ${worker.length} B`);
